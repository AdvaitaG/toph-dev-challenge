// Node 24 strips the fixture's type-only imports. No app/runtime code is changed.
import { readFile, writeFile } from 'node:fs/promises';
import { demoFarm, demoEmployees, demoActivityLogs } from '../src/lib/demo/fixtures.ts';

const quote = (value) => value === null ? 'null' : typeof value === 'boolean' || typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const stamp = '2026-04-22T17:30:00Z';
const fieldNames = [...new Set(demoActivityLogs.map((log) => log.field))];
const fields = fieldNames.map((name, i) => ({ id: `30000000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`, name }));
function insert(table, columns, rows) {
  return `insert into public.${table} (${columns.join(', ')}) values\n${rows.map((row) => `  (${row.map(quote).join(', ')})`).join(',\n')}\non conflict (id) do nothing;\n`;
}
const sql = [
  '-- Generated by node scripts/generate-database-seed.mjs from the unchanged frontend fixtures.',
  '-- Demo snapshot: April 22, 2026. Replay skips existing IDs; clean reset reproduces exact data.',
  '-- No profiles/Auth users, fake media, fake coordinates, or visible tag assignments are seeded.',
  'begin;',
  insert('farms', ['id', 'name', 'timezone', 'created_at', 'updated_at'], [[demoFarm.id, demoFarm.name, demoFarm.timezone, stamp, stamp]]),
  insert('employees', ['id', 'farm_id', 'full_name', 'active', 'created_at', 'updated_at'], demoEmployees.map((e) => [e.id, e.farmId, e.name, e.active, stamp, stamp])),
  insert('fields', ['id', 'farm_id', 'name', 'latitude', 'longitude', 'created_at', 'updated_at'], fields.map((f) => [f.id, demoFarm.id, f.name, null, null, stamp, stamp])),
  insert('activity_logs', ['id', 'farm_id', 'employee_id', 'field_id', 'activity_type', 'activity_date', 'started_at', 'ended_at', 'summary', 'response_accuracy', 'review_status', 'created_at', 'updated_at'], demoActivityLogs.map((l) => [l.id, demoFarm.id, l.employeeId, fields.find((f) => f.name === l.field).id, l.activityType, l.activityDate, l.startedAt, l.endedAt, l.summary, l.responseAccuracy, l.reviewStatus, stamp, stamp])),
  insert('recordings', ['id', 'farm_id', 'activity_log_id', 'recorded_at', 'is_new', 'storage_bucket', 'storage_path', 'duration_seconds', 'created_at', 'updated_at'], demoActivityLogs.map((l, i) => [`40000000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`, demoFarm.id, l.id, l.recordedAt, l.isNew, null, null, null, stamp, stamp])),
  insert('tags', ['id', 'farm_id', 'name', 'created_by', 'created_at', 'updated_at'], [['50000000-0000-4000-8000-000000000001', demoFarm.id, 'Needs Review', null, stamp, stamp]]),
  'commit;\n',
].join('\n');
const path = new URL('../supabase/seed.sql', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== sql) throw new Error('Seed differs from fixtures. Run node scripts/generate-database-seed.mjs.');
  console.log('Seed matches all fixture records.');
} else {
  await writeFile(path, sql);
  console.log('Generated supabase/seed.sql.');
}
